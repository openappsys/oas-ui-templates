export type DictKey = keyof (typeof dict)['zh']

let currentLang: Lang = 'zh'

let oasLocaleReady = false

export function setLang(l: Lang): void {
  currentLang = l
  storeLang(l)
  if (typeof document !== 'undefined') {
    document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en'
  }
  // 组件内建文案跟随应用语言：默认只有 zh-CN，en 语言包需注册一次
  if (!oasLocaleReady) {
    registerLocale(enLocale)
    oasLocaleReady = true
  }
  setLocale(l === 'zh' ? 'zh-CN' : 'en')
}

export function getLang(): Lang {
  return currentLang
}

export function t(key: DictKey): string {
  return dict[currentLang][key] ?? dict.zh[key] ?? key
}

export function loadLang(): Lang {
  return (localStorage.getItem('oas-pm-lang') as Lang) ?? 'zh'
}

export function storeLang(l: Lang): void {
  localStorage.setItem('oas-pm-lang', l)
}

export function dateLocale(): string {
  return currentLang === 'zh' ? 'zh-CN' : 'en-US'
}

const MINUTE = 60_000
const HOUR = 60 * MINUTE
const DAY = 24 * HOUR

/** 相对时间：刚刚 / n 分钟前 / n 小时前 / n 天前；超过 7 天退回日期（通知面板的时间列） */
export function relativeTime(ts: number, now = Date.now()): string {
  const diff = Math.max(0, now - ts)
  if (diff < MINUTE) return t('notifyJustNow')
  if (diff < HOUR) return t('notifyMinutesAgo').replace('{n}', String(Math.floor(diff / MINUTE)))
  if (diff < DAY) return t('notifyHoursAgo').replace('{n}', String(Math.floor(diff / HOUR)))
  if (diff < 7 * DAY) return t('notifyDaysAgo').replace('{n}', String(Math.floor(diff / DAY)))
  return new Date(ts).toLocaleDateString(dateLocale())
}

